#!/bin/sh
# Compile data/knowledgebases.tsv into src/kbinfo.h.
#
#   tools/make_kbinfo.sh -o src/kbinfo.h     (atomic; recommended)
#   tools/make_kbinfo.sh > src/kbinfo.h      (truncates on failure)
#
# Same reasoning as the registry: the browser has to describe a set and know
# whether it is recommended while drawing a frame, so neither can involve
# reading a file it has to locate first or a network call. The TSV stays the
# reviewable source of truth -- a diff against it is readable, which a C
# string table is not.
#
# Needs no network. Run it after editing the TSV, then rebuild.
set -eu

# With -o, write to a temp file and move it into place only on success. The
# shell truncates the target of a `>` redirect before the script runs, so a
# mid-run failure would leave a broken header and the previous contents
# recoverable only from git.
out=""
if [ "${1:-}" = "-o" ]; then
    out=${2:?-o needs a path}
    shift 2
fi

cd "$(dirname "$0")/.."
src=data/knowledgebases.tsv

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT INT TERM
if [ -n "$out" ]; then
    case "$out" in
        /*) ;;                       # absolute: use as given
        *) out="$PWD/$out" ;;        # relative: we just cd'd, so anchor it
    esac
    exec > "$work/out.h"
fi

if [ ! -f "$src" ]; then
    echo "make_kbinfo.sh: missing $src" >&2
    exit 1
fi

cat <<'EOF'
/* kbinfo.h -- GENERATED by tools/make_kbinfo.sh. Do not edit.
 *
 * Regenerate with:  tools/make_kbinfo.sh > src/kbinfo.h
 * The source of truth is data/knowledgebases.tsv.
 *
 * SPDX-License-Identifier: AGPL-3.0-or-later
 * Copyright (C) 2026-present Wanding Zhou
 */
#ifndef _KYCG_KBINFO_H
#define _KYCG_KBINFO_H

#include <stddef.h>

/**
 * What a knowledgebase set is, beyond its name.
 *
 * Keyed on the set name -- the part of a filename before the first dot -- so a
 * single entry covers every genome and platform that publishes that set.
 * `recommend` lists the collections whose recommended selection includes it.
 */
typedef struct {
    const char *set;
    const char *collections;
    const char *recommend;
    const char *title;
    const char *biology;
    const char *source;
    const char *citation;
    const char *processing;
} kycg_kbinfo_t;

static const kycg_kbinfo_t KYCG_KBINFO[] = {
EOF

python3 - "$src" <<'PY'
import sys, csv

path = sys.argv[1]
rows = []
with open(path) as fh:
    for line in fh:
        if line.startswith("#") or not line.strip():
            continue
        # rstrip("\r\n"), not just "\n": a TSV saved with CRLF would otherwise
        # carry a trailing CR into the last field of every row, and c() escapes
        # only backslash and quote, so it would land raw inside a C string.
        parts = line.rstrip("\r\n").split("\t")
        if parts and parts[0] == "set":      # the header row
            continue
        while len(parts) < 8:
            parts.append("")
        rows.append(parts[:8])

def c(s):
    # .strip() removes an interior-field CR too, for the same reason.
    s = (s or "").strip()
    # "?" is an acknowledged gap, not an empty field. Rendering it rather than
    # dropping it is the difference between "nobody knows" and "nobody looked"
    # -- and the browser omits empty fields entirely, so dropping it would say
    # the wrong one.
    if s == "?":
        s = "not recorded"
    return s.replace("\\", "\\\\").replace('"', '\\"')

for r in sorted(rows, key=lambda x: x[0].lower()):
    print('    { "%s", "%s", "%s",' % (c(r[0]), c(r[1]), c(r[2])))
    print('      "%s",' % c(r[3]))
    print('      "%s",' % c(r[4]))
    print('      "%s",' % c(r[5]))
    print('      "%s",' % c(r[6]))
    print('      "%s" },' % c(r[7]))
PY

cat <<'EOF'
    { NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL }
};

/** Metadata for a set name, or NULL when we have none recorded. */
static inline const kycg_kbinfo_t *kycg_kbinfo_find(const char *set) {
    if (!set) return NULL;
    for (const kycg_kbinfo_t *k = KYCG_KBINFO; k->set; ++k) {
        const char *a = k->set, *b = set;
        while (*a && *b) {
            char ca = *a, cb = *b;
            if (ca >= 'A' && ca <= 'Z') ca = (char)(ca - 'A' + 'a');
            if (cb >= 'A' && cb <= 'Z') cb = (char)(cb - 'A' + 'a');
            if (ca != cb) break;
            ++a; ++b;
        }
        if (!*a && !*b) return k;
    }
    return NULL;
}

/** Is `set` part of `collection`'s recommended selection? */
static inline int kycg_kbinfo_recommended(const char *set,
                                          const char *collection) {
    const kycg_kbinfo_t *k = kycg_kbinfo_find(set);
    if (!k || !k->recommend || !*k->recommend || !collection) return 0;

    size_t want = 0;
    while (collection[want]) ++want;

    const char *p = k->recommend;
    while (*p) {
        const char *comma = p;
        while (*comma && *comma != ',') ++comma;
        size_t len = (size_t)(comma - p);
        if (len == want) {
            size_t i = 0;
            while (i < len && p[i] == collection[i]) ++i;
            if (i == len) return 1;
        }
        if (!*comma) break;
        p = comma + 1;
    }
    return 0;
}

#endif /* _KYCG_KBINFO_H */
EOF

if [ -n "$out" ]; then
    exec >&2
    mv "$work/out.h" "$out"
    echo "make_kbinfo.sh: wrote $out"
fi
