#!/usr/bin/env bash
## Generate src/registry.h from YAME's shared file table.
##
##   tools/make_registry.sh -o src/registry.h     (atomic; recommended)
##   tools/make_registry.sh --check               (CI: regenerate and compare)
##
## WHY THIS LIVES IN KYCG
##   kycg depends on YAME, so YAME cannot own kycg's struct definitions: a
##   field on kycg's own public type used to be a YAME commit. YAME keeps the
##   catalog (tools/registry/files.tsv) and the lookups (lib.sh); the
##   projection of that table into THIS repo's header is ours. See the
##   labjournal ROADMAP entry "each tool emits its own registry".
##
## WHAT IT PROJECTS
##   kycg's universe is three globs over store_path: the knowledgebase sets
##   under <target>/KYCG/, the whole-genome row lists, and the array probe
##   orderings. Everything else in the table belongs to another tool.
##
## OFFLINE. Reads the checked-in table and nothing else; no network, no cache.
## Regeneration is byte-reproducible, which is what --check asserts.
set -euo pipefail

## Byte-reproducibility is the whole contract here -- CI regenerates and
## compares -- so the collation every sort and comparison uses must not depend
## on the developer's locale. Without this, `sort` orders the tag summary one
## way under en_US.UTF-8 and another under C, and the header is "stale" on any
## machine whose locale differs from the one that last generated it.
export LC_ALL=C

cd "$(dirname "$0")/.."
. external/YAME/tools/registry/lib.sh

out=""; check=0
case ${1:-} in
  -o)      out=${2:?-o needs a path} ;;
  --check) check=1 ;;
  "")      ;;
  *)       echo "usage: $0 [-o src/registry.h | --check]" >&2; exit 2 ;;
esac

## Zenodo deposits are provenance for the whole-genome collections and are
## kycg's alone -- files.tsv deliberately does not carry them (design §2.8).
## genome<TAB>record<TAB>doi
zenodo() {
  cat <<'Z'
hg38	18175838	10.5281/zenodo.18175837
mm10	18175656	10.5281/zenodo.18175655
mm39		
Z
}
zen_field() { zenodo | /usr/bin/awk -F'\t' -v g="$1" -v i="$2" '$1==g{print $i}'; }

## A C string body: backslashes and quotes escaped, newlines flattened. The
## prose columns are free text from the shared table, so neither is hypothetical.
cesc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g' | tr '\n' ' '; }

## A C string, or NULL for an empty cell.
cstr() { if [ -z "$1" ]; then printf 'NULL'; else printf '"%s"' "$1"; fi; }

## The whole of kycg's universe as ONE yame_asset_file_t[] -- the shape the
## shared API takes (yame_fetch_cfg_t.files), so kycg hands its own registry
## to yame_store_resolve without converting anything. Rows are emitted grouped
## by store directory, and each collection records where its slice starts and
## how long it is; the table itself ends with the zeroed terminator
## YAME_NFILES subtracts.
##
## One C row. The four prose columns come from the same table that feeds
## kbinfo.h, so a set is described once for the whole suite.
emit_row() {   ## row
  local row=$1
  printf '    { "%s", "%s",\n      "%s",\n      "%s", %s,\n      "%s", "%s", "%s", "%s" },\n' \
    "$(field "$row" key)" "$(field "$row" store_path)" \
    "$(url_of "$(field "$row" key)")" "$(field "$row" sha256)" \
    "$(field "$row" size)" \
    "$(cesc "$(field "$row" title)")" "$(cesc "$(field "$row" description)")" \
    "$(cesc "$(field "$row" source)")" "$(cesc "$(field "$row" citation)")"
}

emit() {
  ## Collect the groups first, in emission order, so the offsets the two
  ## registries quote are computed once and cannot drift from the table.
  local plats gens
  plats=$(files_of '*/*.ordering.tsv.gz' | cut -f2 | cut -d/ -f1)
  gens=$(files_of '*/cpg_nocontig.cr'    | cut -f2 | cut -d/ -f1)

  cat <<'EOF'
/* registry.h -- GENERATED by tools/make_registry.sh. Do not edit.
 *
 * Regenerate with:  make registry
 * Check with:       tools/make_registry.sh --check
 *
 * A projection of YAME's shared file table (external/YAME/tools/registry/
 * files.tsv) into the shape the suite shares: one yame_asset_file_t per file,
 * in one array, so kycg can hand its own registry straight to the shared
 * resolver (yame_fetch_cfg_t.files) without converting anything. kycg takes
 * the knowledgebase sets, the whole-genome row lists and the array probe
 * orderings, and nothing else.
 *
 * EVERY FILE CARRIES ITS OWN DIGEST, and that digest is what a download is
 * verified against. There is no directory anchor and no trust in a fetched
 * manifest: a file is what this header says it is, or it is discarded. A set
 * published upstream with no row here cannot be verified, so it is not
 * offered -- the table is the authority for what exists.
 *
 * The two registries below do not own their files; they name a slice of
 * KYCG_FILES. Rows are grouped by store directory, so a slice is contiguous.
 *
 * SPDX-License-Identifier: AGPL-3.0-or-later
 * Copyright (C) 2026-present Wanding Zhou
 */
#ifndef _KYCG_REGISTRY_H
#define _KYCG_REGISTRY_H

#include <stdint.h>
#include <stddef.h>
#include "assets.h"   /* yame_asset_file_t, YAME_NFILES */

/* One array platform. `sets` is the slice under <platform>/KYCG/, `comp` the
 * probe ordering that lands one level up and gives a row index its identity. */
typedef struct {
    const char              *platform;
    uint64_t                 rows;      /* probes in the ordering */
    uint64_t                 n_sets;    /* .cm sets, excluding .idx sidecars */
    const yame_asset_file_t *sets;
    size_t                   n_set_files;  /* rows in the slice, .idx included */
    const yame_asset_file_t *comp;         /* NULL when there is none */
} kycg_array_reg_t;

/* One whole-genome collection. `comp` is cpg_nocontig.cr, which since genomes
 * v4 comes from the genome repository rather than the knowledgebase one --
 * the key on its row says so, and kycg no longer has to care. */
typedef struct {
    const char              *genome;
    uint64_t                 rows;     /* CpGs in cpg_nocontig.cr */
    uint64_t                 n_sets;
    const char              *record;   /* Zenodo, provenance only; may be NULL */
    const char              *doi;
    const yame_asset_file_t *sets;
    size_t                   n_set_files;
    const yame_asset_file_t *comp;
} kycg_seq_reg_t;

static const yame_asset_file_t KYCG_FILES[] = {
EOF

  ## ---- the one table, grouped by store directory ----------------------- ##
  local off=0 coll row n
  : > "$tmpidx"
  for coll in $plats $gens; do
    n=0
    while IFS= read -r row; do
      [ -n "$row" ] || continue
      emit_row "$row"; n=$((n + 1))
    done < <(files_of "$coll/KYCG/*")
    printf '%s\tsets\t%s\t%s\n' "$coll" "$off" "$n" >> "$tmpidx"
    off=$((off + n))

    ## the companion: the ordering for a platform, the row list for a genome
    while IFS= read -r row; do
      [ -n "$row" ] || continue
      emit_row "$row"
      printf '%s\tcomp\t%s\t1\n' "$coll" "$off" >> "$tmpidx"
      off=$((off + 1))
    done < <(files_of "$coll/*.ordering.tsv.gz" "$coll/cpg_nocontig.cr")
  done

  ## The terminator. Without it YAME_NFILES reports one file too few and the
  ## row the table's order put last silently disappears.
  printf '    { NULL, NULL, NULL, NULL, 0, NULL, NULL, NULL, NULL }\n};\n\n'
  printf '#define KYCG_N_FILES YAME_NFILES(KYCG_FILES)\n\n'

  ## ---- the two registries, as slices ----------------------------------- ##
  idx_of() {   ## coll kind field   (field 3 = offset, 4 = count)
    /usr/bin/awk -F'\t' -v c="$1" -v k="$2" -v f="$3" \
      '$1==c && $2==k {print $f}' "$tmpidx"
  }

  printf 'static const kycg_array_reg_t KYCG_ARRAY_REGISTRY[] = {\n'
  local nsets o cnt
  for coll in $plats; do
    nsets=$(files_of "$coll/KYCG/*" | cut -f2 | grep -c '\.cm$' || true)
    o=$(idx_of "$coll" sets 3); cnt=$(idx_of "$coll" sets 4)
    row=$(idx_of "$coll" comp 3)
    printf '    { "%s", %s, %s, KYCG_FILES + %s, %s, %s },\n' \
      "$coll" "$(files_of "$coll/*.ordering.tsv.gz" | head -1 | cut -f5)" \
      "$nsets" "$o" "$cnt" \
      "$([ -n "$row" ] && echo "KYCG_FILES + $row" || echo NULL)"
  done
  printf '    { NULL, 0, 0, NULL, 0, NULL }\n};\n\n'

  printf 'static const kycg_seq_reg_t KYCG_SEQ_REGISTRY[] = {\n'
  for coll in $gens; do
    nsets=$(files_of "$coll/KYCG/*" | cut -f2 | grep -c '\.cm$' || true)
    o=$(idx_of "$coll" sets 3); cnt=$(idx_of "$coll" sets 4)
    row=$(idx_of "$coll" comp 3)
    printf '    { "%s", %s, %s, %s, %s, KYCG_FILES + %s, %s, %s },\n' \
      "$coll" "$(files_of "$coll/cpg_nocontig.cr" | head -1 | cut -f5)" \
      "$nsets" "$(cstr "$(zen_field "$coll" 2)")" "$(cstr "$(zen_field "$coll" 3)")" \
      "$o" "$cnt" \
      "$([ -n "$row" ] && echo "KYCG_FILES + $row" || echo NULL)"
  done
  printf '    { NULL, 0, 0, NULL, NULL, NULL, 0, NULL }\n};\n\n'

  ## ---- what this build can verify, for --version ------------------------ ##
  printf '/* The upstream sources this build carries rows from, and their tags. */\n'
  printf '#define KYCG_REGISTRY_TAGS "%s"\n\n' \
    "$(files_of '*/KYCG/*' '*/cpg_nocontig.cr' '*/*.ordering.tsv.gz' |
       cut -f1 | /usr/bin/awk -F'[@:]' '{print $1"@"$2}' |
       sed 's#^[^/]*/##' | sed 's/_[a-z0-9]*@/@/' | sort -u | tr '\n' ' ' |
       sed 's/ $//')"

  printf '#endif /* _KYCG_REGISTRY_H */\n'
}

tmpidx=$(mktemp); trap 'rm -f "$tmpidx"' EXIT

if [ "$check" = 1 ]; then
  tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT
  emit > "$tmp"
  if cmp -s "$tmp" src/registry.h; then
    echo "registry: src/registry.h is current"
  else
    echo "registry: src/registry.h is STALE -- run tools/make_registry.sh -o src/registry.h" >&2
    diff -u src/registry.h "$tmp" | head -20 >&2
    exit 1
  fi
elif [ -n "$out" ]; then
  ## Atomic: a failed run never leaves a half-written header that compiles.
  tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT
  emit > "$tmp"
  mv "$tmp" "$out"
  trap - EXIT
  echo "registry: wrote $out"
else
  emit
fi
