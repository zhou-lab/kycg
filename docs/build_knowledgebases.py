#!/usr/bin/env python3
"""Regenerate the Knowledgebases tab of docs/index.html, and its llms.txt list.

What a knowledgebase IS comes from the suite's file table,
external/YAME/tools/registry/files.tsv, at the pinned submodule -- the same
rows src/registry.h and src/kbinfo.h are projected from, so the page lists
exactly what the binary fetches. What is INSIDE each .cm (its sets and their
sizes) is not in the table; tools/make_kb_counts.sh reads the store once and
writes docs/knowledgebase_counts.tsv, which is committed, so this needs no
store and no network.

    docs/build_knowledgebases.py            rewrite both files in place
    docs/build_knowledgebases.py --check    exit 1 if either is behind

A knowledgebase in the table with no counts is an error: a registry bump that
adds or renames a .cm must re-run tools/make_kb_counts.sh.
"""
import html, os, sys
from collections import OrderedDict, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "external", "YAME", "tools", "registry", "files.tsv")
COUNTS = os.path.join(ROOT, "docs", "knowledgebase_counts.tsv")
## which of the paper's four categories each knowledgebase belongs to
CATFILE = os.path.join(ROOT, "docs", "kb_categories.tsv")
PAGE = os.path.join(ROOT, "docs", "index.html")
LLMS = os.path.join(ROOT, "docs", "llms.txt")
BEGIN = ("<!-- knowledgebases:begin (generated by docs/build_knowledgebases.py;"
         " edit YAME's files.tsv) -->")
END = "<!-- knowledgebases:end -->"
LBEGIN = "<!-- knowledgebases:begin -->"
LEND = "<!-- knowledgebases:end -->"

## the order collections are read in: genomes first, then arrays newest first
ORDER = ["hg38", "mm10", "mm39", "MSA", "EPICv2", "EPIC", "HM450", "HM27",
         "MM285", "Mammal40"]


def read_registry():
    rows, kbs = {}, defaultdict(list)
    with open(TSV) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            f = line.rstrip("\n").split("\t")
            f += [""] * (10 - len(f))
            key, path, _, size, nrow, kind, title, desc, src, cite = f[:10]
            coll = path.split("/")[0]
            if nrow:
                rows[coll] = (int(nrow), kind)
            if "/KYCG/" in path and path.endswith(".cm"):
                fname = path.split("/")[-1]
                kbs[coll].append(dict(
                    file=fname, name=fname.split(".")[0],
                    version=fname.split(".")[1] if fname.count(".") > 1 else "",
                    tag=key.rsplit(":", 1)[0], size=int(size or 0),
                    title=title, desc=desc, src=src, cite=cite))
    return rows, kbs


def read_counts():
    """(collection, file) -> list of (set, n), or a tiling summary dict.

    tools/make_kb_counts.sh writes one row per set, except for a tiling
    (genomic bins, k-mers: too many sets to list), which gets one row with
    set "*" and the number of sets, the size range and the first and last
    names."""
    sets = defaultdict(list)
    with open(COUNTS) as fh:
        next(fh)
        for line in fh:
            coll, fname, name, n, lo, med, hi, first, last = \
                line.rstrip("\n").split("\t")
            if name == "*":
                sets[(coll, fname)] = dict(n=int(n), min=int(lo),
                                           median=int(med), max=int(hi),
                                           first=first, last=last)
            else:
                sets[(coll, fname)].append((name, int(n)))
    return dict(sets)


def n_sets(ss):
    return ss["n"] if isinstance(ss, dict) else len(ss)


def esc(s):
    return html.escape(s, quote=True)


def mb(nbytes):
    if nbytes < 1e3:
        return "<1 KB"
    return f"{nbytes / 1e6:.1f} MB" if nbytes >= 1e5 else f"{nbytes / 1e3:.0f} KB"


def colls_in_order(kbs):
    return [c for c in ORDER if c in kbs] + sorted(set(kbs) - set(ORDER))


CATS = ["Sequence features", "Genomic features", "Trait associates",
        "Technical associates"]
UNCAT = "Uncategorized"


def read_categories():
    """knowledgebase -> category, from docs/kb_categories.tsv."""
    cat = {}
    with open(CATFILE) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            name, category, _ = line.rstrip("\n").split("\t")
            if category not in CATS:
                sys.exit(f"build_knowledgebases: {name}: unknown category "
                         f"'{category}' in {os.path.relpath(CATFILE, ROOT)}")
            cat[name] = category
    return cat


def by_category(items, cat):
    """[(category, [kb, ...])] in the paper's order, Uncategorized last."""
    groups = OrderedDict((c, []) for c in CATS + [UNCAT])
    for k in sorted(items, key=lambda k: k["name"].lower()):
        groups[cat.get(k["name"], UNCAT)].append(k)
    return [(c, v) for c, v in groups.items() if v]


def render_kb(k, ss, c, nrow, unit, category):
    out = []
    title = k["title"] or k["name"]
    ns = n_sets(ss)
    out.append(f'    <details class="kb" data-cat="{esc(category)}">')
    out.append(
        f'      <summary><b>{esc(k["name"])}</b> <span class="kb-t">'
        f'{esc(title)}</span><span class="kb-n">{ns:,} '
        f'set{"s" if ns != 1 else ""} · {mb(k["size"])}</span>'
        f'</summary>')
    if k["desc"]:
        out.append(f'      <p class="kb-d">{esc(k["desc"])}</p>')
    meta = []
    if k["src"]:
        meta.append(f'<b>Source</b> {esc(k["src"])}')
    if k["cite"]:
        meta.append(f'<b>Cite</b> {esc(k["cite"])}')
    meta.append(f'<b>File</b> <code>{esc(k["file"])}</code>')
    out.append('      <p class="kb-m">' + " · ".join(meta) + "</p>")
    if isinstance(ss, dict):
        out.append(
            f'      <p class="kb-m">A tiling: {ss["n"]:,} sets, '
            f'<code>{esc(ss["first"])}</code> … '
            f'<code>{esc(ss["last"])}</code>, too many to list. '
            f'{unit} per set: min {ss["min"]:,}, median '
            f'{ss["median"]:,}, max {ss["max"]:,}.</p>')
        out.append('    </details>')
        return out
    total = sum(n for _, n in ss)
    out.append('      <div class="scroll"><table class="t">')
    out.append(f'        <tr><th>Set</th><th class="num">{unit}</th>'
               f'<th class="num">% of {c}</th></tr>')
    for name, n in ss:
        pct = 100 * n / nrow if nrow else 0
        out.append(f'        <tr><td><code>{esc(name)}</code></td>'
                   f'<td class="num">{n:,}</td>'
                   f'<td class="num">{pct:.2f}</td></tr>')
    out.append(f'        <tr class="kb-sum"><td>{len(ss)} sets</td>'
               f'<td class="num">{total:,}</td><td></td></tr>')
    out.append('      </table></div>')
    out.append('    </details>')
    return out


def render(rows, kbs, sets, cat):
    out = [BEGIN]
    n_kb = sum(len(v) for v in kbs.values())
    n_set = sum(n_sets(sets[(c, k["file"])]) for c in kbs for k in kbs[c])
    ## head counts, as chips: totals, then knowledgebases per category
    per_cat = defaultdict(int)
    for c in kbs:
        for k in kbs[c]:
            per_cat[cat.get(k["name"], UNCAT)] += 1
    chips = [(len(kbs), "collections"), (n_kb, "knowledgebases"),
             (n_set, "sets")]
    chips += [(per_cat[c], c.lower()) for c in CATS + [UNCAT] if per_cat[c]]
    out.append('<div class="kb-chips">' + "".join(
        f'<span class="kb-chip"><b>{n:,}</b>{esc(label)}</span>'
        for n, label in chips) + "</div>")
    out.append(
        '<div class="kb-find"><input id="kb-q" type="search" '
        'placeholder="Filter by name, title, description, set or category" '
        'aria-label="Filter knowledgebases" autocomplete="off">'
        '<span id="kb-hits"></span></div>')
    out.append('<p class="kb-jump">' + " · ".join(
        f'<a href="#kb-{c}">{c}</a>' for c in colls_in_order(kbs)) + "</p>")
    for i, c in enumerate(colls_in_order(kbs)):
        nrow, kind = rows.get(c, (0, ""))
        unit = "CpGs" if kind == "genome" else "probes"
        tags = sorted({k["tag"] for k in kbs[c]})
        ns_c = sum(n_sets(sets[(c, k["file"])]) for k in kbs[c])
        out.append(f'<details class="full kb-coll" id="kb-{c}"'
                   f'{" open" if i == 0 else ""}>')
        out.append(
            f'  <summary><h2>{c} <span class="m">— '
            f'{"whole genome" if kind == "genome" else "array"}, '
            f'{nrow:,} {unit} · {len(kbs[c])} knowledgebases · '
            f'{ns_c:,} sets</span></h2></summary>')
        out.append('  <p class="kb-tag">From ' + ", ".join(
            f'<code class="inl">{esc(t)}</code>' for t in tags) + "</p>")
        for category, items in by_category(kbs[c], cat):
            out.append(f'  <div class="kb-cat">')
            out.append(f'    <h3>{esc(category)} <span class="m">'
                       f'{len(items)}</span></h3>')
            for k in items:
                out += render_kb(k, sets[(c, k["file"])], c, nrow, unit,
                                 category)
            out.append('  </div>')
        out.append('</details>')
    out.append(END)
    return "\n".join(out)


def render_llms(rows, kbs, sets, cat):
    out = [LBEGIN, "## Knowledgebases", "",
           "What `kycg fetch` offers, per collection, grouped by the KnowYourCG",
           "paper's four categories: each knowledgebase with its number of sets",
           "(records or states in the .cm). Set names and sizes are on the",
           "page's Knowledgebases tab.", ""]
    for c in colls_in_order(kbs):
        nrow, kind = rows.get(c, (0, ""))
        unit = "CpGs" if kind == "genome" else "probes"
        tags = ", ".join(sorted({k["tag"] for k in kbs[c]}))
        out.append(f"- {c} ({nrow:,} {unit}; {tags})")
        for category, items in by_category(kbs[c], cat):
            names = ", ".join(
                f'{k["name"]} ({n_sets(sets[(c, k["file"])]):,})'
                for k in items)
            out.append("  " + wrap(f"{category}: {names}", indent="    "))
    out.append(LEND)
    return "\n".join(out)


def wrap(s, width=77, indent="  "):
    words, lines, cur = s.split(" "), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = indent + w
        else:
            cur = f"{cur} {w}" if cur else w
    lines.append(cur)
    return "\n".join(lines)


def splice(text, begin, end, body, where):
    i, j = text.find(begin), text.find(end)
    if i < 0 or j < 0:
        sys.exit(f"build_knowledgebases: markers missing in {where}")
    return text[:i] + body + text[j + len(end):]


def main():
    check = "--check" in sys.argv[1:]
    rows, kbs = read_registry()
    sets = read_counts()
    cat = read_categories()
    missing = [f"{c}/{k['file']}" for c in kbs for k in kbs[c]
               if (c, k["file"]) not in sets]
    if missing:
        sys.exit("build_knowledgebases: no counts for " + ", ".join(missing) +
                 "; re-run tools/make_kb_counts.sh")
    stale = []
    for path, begin, end, body in (
            (PAGE, BEGIN, END, render(rows, kbs, sets, cat)),
            (LLMS, LBEGIN, LEND, render_llms(rows, kbs, sets, cat))):
        old = open(path).read()
        new = splice(old, begin, end, body, path)
        if new == old:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            open(path, "w").write(new)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        sys.exit("stale: " + ", ".join(stale) +
                 "; run docs/build_knowledgebases.py")


if __name__ == "__main__":
    main()
